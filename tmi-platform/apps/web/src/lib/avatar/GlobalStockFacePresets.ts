export function getStockFacePresetById(id: string): StockFacePreset | undefined {
  const resolvedId = LEGACY_FACE_PRESET_MAP[id] ?? id;
  return GLOBAL_STOCK_FACE_PRESETS.find((p) => p.id === resolvedId);
}

/** Filter presets by category, gender, or search term */
export function searchStockFaces(
  query?: string,
  category?: FaceMorphologyCategory | "all",
  gender?: "female" | "male" | "unisex" | "all",
  ageGroup?: "youth" | "adult" | "mature" | "all",
): StockFacePreset[] {
  let list = GLOBAL_STOCK_FACE_PRESETS;
  if (category && category !== "all") {
    list = list.filter((p) => p.category === category);
  }
  if (gender && gender !== "all") {
    list = list.filter((p) => p.gender === gender || p.gender === "unisex");
  }
  if (ageGroup && ageGroup !== "all") {
    list = list.filter((p) => p.ageGroup === ageGroup || p.tags.includes(ageGroup));
  }
  if (query && query.trim()) {
    const q = query.toLowerCase().trim();
    list = list.filter(
      (p) =>
        p.label.toLowerCase().includes(q) ||
        p.description.toLowerCase().includes(q) ||
        p.tags.some((t) => t.toLowerCase().includes(q)),
    );
  }
  return list;
}

